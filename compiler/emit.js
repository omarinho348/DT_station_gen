// The compiler: factory.json → readable Three.js files, one per station plus a line file, written
// from fixed templates (Claude.md rule 1: no code ever comes from the LLM). Deterministic: the
// same factory.json always gives the same bytes. Knows no catalog component by name (rule 6):
// component types are copied from the IR into the emitted calls.
//
//   compileFactory(registry, data, { source, libPath }) → { line, folder, files: [{ name, content }], timing }
//
// generated/<folder>/
//   <station>.js   `station` (what the station does: ports, process ops, status, signals; shell
//                  already merged in) and `build({ registry, ctx })`, which builds every machine
//                  from the catalog and places it in the station's own frame
//   line.js        the line conventions, product, graph edges, the timing table and
//                  `createLine({ materials })`, which plays the stations with lib/line/Line.js
// Layout is not written into the files: lib/line/layout.js places the stations when the line is
// built, from the same data (Claude.md §6.5); the line file lists the positions as a comment.
import { expandFactory } from './expand.js';
import { lineTiming } from './timing.js';
import { jsString, toJs } from './jsLiteral.js';

/** The marker every emitted file carries (the writer only ever replaces files that have it). */
export const GENERATED_MARK = 'Generated by compiler/emit.js';

const f2 = (v) => v.toFixed(2);

/** 'printerLine' → 'printer-line' (the folder under generated/). */
export function lineFolder(id) {
  return id.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function header(title, source) {
  return [
    `// ${title}`,
    `// ${GENERATED_MARK} from ${source ?? 'a factory.json'}.`,
    '// Do not edit: change the factory.json and compile again (npm run compile).',
  ];
}

/** First sentence of a catalog summary, for a comment (cut at a word past 80 characters). */
function shortSummary(summary) {
  const first = String(summary ?? '').split(/(?<=\.)\s/)[0].replace(/\.$/, '');
  if (first.length <= 80) return first;
  return `${first.slice(0, 78).replace(/[\s,;:]+\S*$/, '')}...`;
}

/** An angle as code: exact multiples of π as Math.PI expressions, anything else as the number. */
export function angle(v) {
  for (const d of [1, 2, 3, 4, 6, 8, 12]) {
    for (let n = -2 * d; n <= 2 * d; n += 1) {
      if (n === 0 || (n * Math.PI) / d !== v) continue;
      const num = n === 1 ? 'Math.PI' : n === -1 ? '-Math.PI' : `${n} * Math.PI`;
      return d === 1 ? num : `${num} / ${d}`;
    }
  }
  return String(v);
}

const columns = (rows) => {
  const widths = rows[0].map((_, i) => Math.max(...rows.map((r) => String(r[i]).length)));
  return rows.map((r) => r.map((c, i) => (i === r.length - 1 ? String(c) : String(c).padEnd(widths[i]))).join('  ').trimEnd());
};

// Names a station module may not take in line.js: JS reserved words and the file's own bindings.
const TAKEN = new Set(`break case catch class const continue debugger default delete do else enum export extends false
  finally for function if import in instanceof new null return super switch this throw true try typeof var void while
  with yield let static implements interface package private protected public await arguments eval undefined NaN
  Infinity id title runSize conventions product edges timing stations createLine catalog Line`.split(/\s+/));

/** The import name of a station's module in line.js. */
export const moduleName = (id) => (TAKEN.has(id) ? `${id}Station` : id);

const vec = (p) => `[${p.map((v) => String(v)).join(', ')}]`;

// ---- Station file --------------------------------------------------------------------------------

function emitStation(registry, { station, own, shellType, timing, source }) {
  const { equipment, ...data } = station;
  const name = [station.code, station.title ?? station.id].filter(Boolean).join(' ');
  const t = timing;
  const origin = (e) => (own.has(e.id) ? 'station' : `shell ${shellType}`);
  const table = columns([
    ['id', 'type', 'from', 'position', 'turn'],
    ...equipment.map((e) => [e.id, e.type, origin(e), vec(e.position), e.rotationY ? `${f2(e.rotationY)} rad` : '']),
  ]);

  const lines = [
    ...header(name, source),
    '//',
    `// Cycle ${f2(t.cycleTime)} s (intake ${f2(t.intake)} + process ${f2(t.process)} + output ${f2(t.output)}), ${t.steps} steps`,
    '// (a decision on a fact only known while a unit plays is timed by its planAs branch, else its longest).',
    '// Equipment, in the station\'s own frame (metres; product flows +X, conveyor on z = 0, walkway +Z):',
    ...table.map((row) => `//   ${row}`),
    'import * as THREE from \'three\';',
    '',
    '/** What the station does (played by lib/station/StationCycle.js): ports, process ops, status, signals. */',
    `export const station = ${toJs(data)};`,
    '',
    '/**',
    ' * Builds the station\'s machines from the catalog and places them in the station frame.',
    ' * @param {object} o',
    ' * @param {object} o.registry  the catalog (components, products, ops)',
    ' * @param {object} o.ctx       build context: materials, belt height',
    ' * @returns {{ root: THREE.Group, equipment: object }}',
    ' */',
    'export function build({ registry, ctx }) {',
    '  const root = new THREE.Group();',
    `  root.name = ${jsString(name)};`,
    '  const equipment = {};',
  ];
  for (const e of equipment) {
    const def = registry.getComponent(e.type);
    const ref = `equipment.${e.id}`;
    const ctx = e.beltHeight !== undefined ? `{ ...ctx, beltHeight: ${e.beltHeight} }` : 'ctx';
    const call = `  ${ref} = registry.buildComponent(${jsString(e.type)}, `;
    // The parameters stay on the call's line when they fit (the context argument follows them).
    const params = toJs(e.params ?? {}, { indent: 2, col: call.length + ctx.length + 3 });
    lines.push(
      '',
      `  // ${e.id}: ${shortSummary(def.summary)}${own.has(e.id) ? '' : ` (shell ${shellType})`}`,
      `${call}${params}, ${ctx});`,
    );
    if (e.position.some((v) => v !== 0)) lines.push(`  ${ref}.root.position.set(${e.position.join(', ')});`);
    if (e.rotationY) lines.push(`  ${ref}.root.rotation.y = ${angle(e.rotationY)};`);
    lines.push(`  root.add(${ref}.root);`);
  }
  lines.push('', '  return { root, equipment };', '}', '');
  return lines.join('\n');
}

// ---- Line file -----------------------------------------------------------------------------------

function emitLine({ expanded, timing, source, libPath, stationFiles }) {
  const { line, conventions } = expanded;
  const order = timing.layout.order;
  const stationRows = timing.stations.map((s) => [[s.code, s.title].filter(Boolean).join(' '), f2(s.cycleTime), String(s.steps), `x ${f2(timing.layout.stations[s.id].x)}`]);
  const table = columns([['station', 'cycle s', 'steps', 'placed at'], ...stationRows]);
  const transfers = timing.transfers.map((t) => `//   ${t.from} → ${t.to}: ${f2(t.distance)} m, ${f2(t.duration)} s`);
  const imports = order.map((id) => `import * as ${moduleName(id)} from './${stationFiles[id]}';`);
  const timingData = {
    takt: timing.takt,
    bottleneck: timing.bottleneck,
    leadTime: timing.leadTime,
    runTime: timing.runTime,
    stations: Object.fromEntries(timing.stations.map((s) => [s.id, { intake: s.intake, process: s.process, output: s.output, cycleTime: s.cycleTime, steps: s.steps }])),
    transfers: timing.transfers.map((t) => ({ from: t.from, to: t.to, distance: t.distance, duration: t.duration })),
  };
  // Plain data (the frozen defaults would print the same, but a literal is easier to read).
  const conventionData = JSON.parse(JSON.stringify(conventions));

  return [
    ...header(`${line.title} (${line.id})`, source),
    '//',
    `// ${order.length} stations in flow order (placed by lib/line/layout.js when the line is built):`,
    ...table.map((row) => `//   ${row}`),
    '// Transfers:',
    ...transfers,
    `// Takt ${f2(timing.takt)} s (bottleneck: ${timing.bottleneck.kind} ${timing.bottleneck.id}); one unit through the line ${f2(timing.leadTime)} s;`,
    `// A run of ${line.runSize} about ${f2(timing.runTime)} s. Decisions on facts only known while a unit`,
    '// plays (a verdict) are timed by their planAs branch, else their longest, here; one-off branches',
    '// (a full pallet leaving) are not in the estimate.',
    `import { registry as catalog } from '${libPath}/components/index.js';`,
    `import '${libPath}/products/index.js';`,
    `import '${libPath}/ops/index.js';`,
    `import { Line } from '${libPath}/line/index.js';`,
    ...imports,
    '',
    `export const id = ${jsString(line.id)};`,
    `export const title = ${jsString(line.title)};`,
    `export const runSize = ${line.runSize};`,
    '',
    '/** Line conventions (metres, seconds) with this factory\'s overrides. */',
    `export const conventions = ${toJs(conventionData)};`,
    '',
    '/** The product every unit is (catalog type and parameters). */',
    `export const product = ${toJs(line.product)};`,
    '',
    '/** The graph: which output port feeds which input port, and the transport between them. */',
    `export const edges = ${toJs(line.edges)};`,
    '',
    '/** Dry timing from compiler/timing.js (seconds). */',
    `export const timing = ${toJs(timingData)};`,
    '',
    // The factory's order, not flow order: the line builds and updates its stations in this order, so
    // the compiled line plays exactly as the one built from the IR (a reviewer check, step 7.4).
    '/** The stations in the factory\'s order (the order the line builds and updates them): each `{ station, build }`. */',
    `export const stations = [${expanded.line.stations.map((s) => moduleName(s.id)).join(', ')}];`,
    '',
    '/**',
    ' * Builds the line: every station from its file, laid out and chained through its ports.',
    ' * @param {object} [o]',
    ' * @param {object} [o.materials]  shared materials (lib/core/materials.js)',
    ' * @param {object} [o.registry]   the catalog (default: the whole library)',
    ' * @param {Function} [o.facts]    (unit) → extra facts for `decide`',
    ' * @param {Function} [o.onUpdate] (line) after every update',
    ' * @returns {Line}',
    ' */',
    'export function createLine({ materials, registry = catalog, facts = null, onUpdate = null } = {}) {',
    '  return new Line({',
    '    registry,',
    '    line: {',
    '      id, title, runSize, product, edges,',
    '      transferLength: conventions.transferLength,',
    '      stations: stations.map((s) => ({ ...s.station, build: s.build })),',
    '    },',
    '    ctx: { beltHeight: conventions.beltHeight, materials },',
    '    conventions,',
    '    facts,',
    '    onUpdate,',
    '  });',
    '}',
    '',
  ].join('\n');
}

// ---- Compile -------------------------------------------------------------------------------------

/**
 * Compiles a factory.json. Throws FactoryError (with paths) when it does not check.
 * @param {object} registry  the catalog (components, products, ops, shells)
 * @param {object} data      factory.json
 * @param {object} [o]
 * @param {string} [o.source]   the factory.json path shown in the file headers
 * @param {string} [o.libPath]  import path of lib/ seen from the output folder
 */
export function compileFactory(registry, data, { source = null, libPath = '../../lib' } = {}) {
  const expanded = expandFactory(registry, data);
  const timing = lineTiming(registry, expanded.line, { ctx: expanded.ctx, conventions: expanded.conventions });
  const stationFiles = Object.fromEntries(expanded.line.stations.map((s) => [s.id, `${s.id}.js`]));
  const files = [];
  for (const id of timing.layout.order) {
    const station = expanded.line.stations.find((s) => s.id === id);
    const written = expanded.factory.stations.find((s) => s.id === (station.copyOf ?? id)); // a parallel copy is written once
    files.push({
      name: stationFiles[id],
      content: emitStation(registry, {
        station,
        own: new Set(written.equipment.map((e) => e.id)),
        shellType: written.shell?.type ?? null,
        timing: timing.stations.find((s) => s.id === id),
        source,
      }),
    });
  }
  files.push({ name: 'line.js', content: emitLine({ expanded, timing, source, libPath, stationFiles }) });
  return { line: expanded.line.id, folder: lineFolder(expanded.line.id), files, timing, expanded };
}
