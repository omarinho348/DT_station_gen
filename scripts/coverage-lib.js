// The process-coverage table (Claude.md §10, Phase 12): the catalog mapped to DIN 8580, DIN 8593 and
// VDI 2860 (benchmarks/coverage.map.json), checked against the registry and written as markdown.
//
//   checkCoverageMap(map, { components, ops })  → problems (unmapped, unknown, bad codes)
//   coverageTable(map, { components, ops })      → { rows, markdown }
//
// A process counts as covered by a **named** component or op (a catalog machine built for it), by a
// **basic** block only (a tool or axis the Builder must put together as a composite), or **none**
// (a genericMachine placeholder is all the twin can show).

/** All codes the map's standards define, as "DIN 8580:4". */
const codesOf = (map) => Object.entries(map.standards).flatMap(([std, items]) => Object.keys(items).map((k) => `${std}:${k}`));

/**
 * @param {object} map   benchmarks/coverage.map.json
 * @param {object} reg   { components: [{ type, category }], ops: [{ op, basic }] }
 */
export function checkCoverageMap(map, reg) {
  const problems = [];
  const codes = new Set(codesOf(map));
  const check = (kind, names, entries) => {
    for (const n of names) if (!(n in entries)) problems.push(`${kind} "${n}" is in the catalog but not in the map`);
    for (const [n, list] of Object.entries(entries)) {
      if (!names.includes(n)) problems.push(`${kind} "${n}" is in the map but not in the catalog`);
      for (const c of list) if (!codes.has(c)) problems.push(`${kind} "${n}": unknown code "${c}"`);
    }
  };
  check('component', reg.components.map((d) => d.type), map.components);
  check('op', reg.ops.map((d) => d.op), map.ops);
  return problems;
}

const BASIC_CATEGORIES = new Set(['frame', 'axis', 'tool', 'transport', 'buffer']);

export function coverageTable(map, reg) {
  const category = Object.fromEntries(reg.components.map((d) => [d.type, d.category]));
  const basicOp = Object.fromEntries(reg.ops.map((d) => [d.op, d.basic]));
  const rows = [];
  for (const [std, items] of Object.entries(map.standards)) {
    for (const [key, title] of Object.entries(items)) {
      const code = `${std}:${key}`;
      const named = Object.entries(map.components).filter(([t, l]) => l.includes(code) && !BASIC_CATEGORIES.has(category[t])).map(([t]) => t);
      const basic = Object.entries(map.components).filter(([t, l]) => l.includes(code) && BASIC_CATEGORIES.has(category[t])).map(([t]) => t);
      const namedOps = Object.entries(map.ops).filter(([o, l]) => l.includes(code) && !basicOp[o]).map(([o]) => o);
      const basicOps = Object.entries(map.ops).filter(([o, l]) => l.includes(code) && basicOp[o]).map(([o]) => o);
      // DIN 8580's group 4 is covered as well as its best DIN 8593 subgroup.
      const level = named.length || namedOps.length ? 'named' : basic.length || basicOps.length ? 'basic' : 'none';
      rows.push({ standard: std, code: key, title, level, named, basic, namedOps, basicOps });
    }
  }
  const mark = { named: '● named', basic: '◐ basic only', none: '○ none' };
  const list = (xs) => (xs.length ? xs.map((x) => `\`${x}\``).join(', ') : '–');
  const sections = Object.keys(map.standards).map((std) => {
    const mine = rows.filter((r) => r.standard === std);
    const counts = ['named', 'basic', 'none'].map((l) => `${mine.filter((r) => r.level === l).length} ${l === 'basic' ? 'basic only' : l}`).join(', ');
    return `## ${std}

${counts} (of ${mine.length}).

| Code | Process | Coverage | Named components | Basic blocks | Ops |
|---|---|---|---|---|---|
${mine.map((r) => `| ${r.code} | ${r.title} | ${mark[r.level]} | ${list(r.named)} | ${list(r.basic)} | ${list([...r.namedOps, ...r.basicOps])} |`).join('\n')}`;
  });
  const total = rows.length;
  const gaps = rows.filter((r) => r.level === 'none');
  const markdown = `# Process coverage of the catalog

Generated by \`node scripts/coverage.mjs\` from \`benchmarks/coverage.map.json\` and the registry: do not edit, regenerate.

What the twin can show, by **DIN 8580** (manufacturing processes), **DIN 8593** (joining) and **VDI 2860** (handling functions):

- **● named**: a catalog machine or named op made for it (best quality, the Builder picks it by name)
- **◐ basic only**: only basic blocks (a tool, an axis) cover it; the Builder builds it as a \`composite\`
- **○ none**: nothing in the catalog; a \`genericMachine\` placeholder with the right size and timing stands in

**${rows.filter((r) => r.level === 'named').length} of ${total}** processes are covered by named parts, **${rows.filter((r) => r.level === 'basic').length}** by basic blocks only, **${gaps.length}** not at all${gaps.length ? `: ${gaps.map((r) => `${r.standard} ${r.code} (${r.title.split(' (')[0]})`).join('; ')}` : ''}.

${sections.join('\n\n')}

## Not a process

Station furniture and infrastructure (no DIN / VDI process): ${list(Object.entries(map.components).filter(([, l]) => !l.length).map(([t]) => t))}. Ops that only time or switch: ${list(Object.entries(map.ops).filter(([, l]) => !l.length).map(([o]) => o))}.
`;
  return { rows, markdown };
}
