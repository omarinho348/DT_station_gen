#!/usr/bin/env node
// Phase 12 benchmarks (Claude.md §10): runs briefs from benchmarks/briefs/ through the whole pipeline
// (agents/benchmark.js) and writes the results.
//
//   node scripts/benchmark.mjs --set tuning|heldOut [--live] [--brief <name>] [--no-critique] [--no-record]
//   node scripts/benchmark.mjs --report        rewrite benchmarks/results/benchmark.md from the saved runs
//
// Mock mode (the default) replays recorded answers ($0); --live calls the model (budget guard, ledger,
// cache: an answered call is free on a rerun) and records every answer as a fixture, so the same run
// replays in mock mode later. Writes benchmarks/results/runs/<name>.json, benchmarks/results/lines/
// <name>.factory.json and benchmarks/results/benchmark.md.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer, loadEnv } from 'vite';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (k) => (args.includes(k) ? args[args.indexOf(k) + 1] : null);
const index = JSON.parse(readFileSync(join(ROOT, 'benchmarks', 'briefs', 'index.json'), 'utf8'));
const RESULTS = join(ROOT, 'benchmarks', 'results');

function report(summarize) {
  const dir = join(RESULTS, 'runs');
  const runs = existsSync(dir) ? readdirSync(dir).filter((n) => n.endsWith('.json')).map((n) => JSON.parse(readFileSync(join(dir, n), 'utf8'))) : [];
  const n = (v, d = 1) => (Number.isFinite(v) ? String(Number(v.toFixed(d))) : '–');
  const section = (title, names) => {
    const mine = names.map((name) => runs.find((r) => r.name === name)).filter(Boolean);
    if (!mine.length) return `## ${title}\n\nNot run yet.\n`;
    const s = summarize(mine);
    const rows = mine.map((r) => {
      const kinds = ['named', 'composite', 'placeholder'].map((k) => (r.stations ?? []).filter((x) => x.ok && x.kind === k).length).join(' / ');
      const built = (r.stations ?? []).filter((x) => x.ok).length;
      return `| ${r.name} | ${r.stage === 'done' ? '✓' : `✗ ${r.stage}`} | ${built}/${r.planned ?? '–'} | ${(r.stations ?? []).filter((x) => x.ok && x.refusals === 0).length} | ${kinds} | ${r.review ? `${r.review.errors} / ${r.review.warnings}${r.review.plays ? ', plays' : ''}` : '–'} | ${r.simpy?.steadyPerHour ? `${n(r.simpy.steadyPerHour, 0)} / ${r.target?.perHour ?? '–'}` : '–'} | ${r.edit ? (r.edit.success ? '✓' : r.edit.questions ? 'asked' : '✗') : '–'} | ${r.critique?.verdict ?? '–'} | $${n(r.totalCost, 4)} | ${n(r.seconds, 0)} s |`;
    });
    const failures = mine.filter((r) => r.reason).map((r) => `- **${r.name}** (${r.stage}): ${r.reason}`);
    return `## ${title}

| Brief | Line | Stations built | First pass | Named / composite / placeholder | Review errors / warnings | SimPy rate / target (per h) | Edit | Critique | Cost | Time |
|---|---|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

**Totals:**
- lines complete: ${s.linesComplete} of ${s.briefs}
- stations built: ${s.stationsBuilt} of ${s.stationsPlanned}, first pass ${s.firstPassStations} %
- parts: named ${s.parts.named} %, composite ${s.parts.composite} %, placeholder ${s.parts.placeholder} %
- review clean: ${s.reviewOk}; plays to the end: ${s.plays}; SimPy meets the target: ${s.meetsTarget}
- edit success: ${s.editSuccess ?? '–'} %
- critique: ${s.verdicts.fits} fits, ${s.verdicts.concerns} concerns, ${s.verdicts.misfit} misfit
- cost $${n(s.cost.total, 4)} ($${n(s.cost.perLine, 4)} per line); ${n(s.secondsPerLine, 0)} s per line
${failures.length ? `\n**Where runs stopped:**\n${failures.join('\n')}\n` : ''}`;
  };
  const md = `# Benchmark results

Generated by \`node scripts/benchmark.mjs --report\` from \`benchmarks/results/runs/\`. Briefs: \`benchmarks/briefs/\` (the tuning set is used to improve the library and prompts; the held-out set is run without tuning for it). Every approval is given automatically (the brief with its assumptions), so these are the agents' unaided results.

${section('Tuning set', index.tuning)}
${section('Held-out set', index.heldOut)}`;
  mkdirSync(RESULTS, { recursive: true });
  writeFileSync(join(RESULTS, 'benchmark.md'), md);
  return md;
}

const server = await createServer({
  root: ROOT, logLevel: 'error', appType: 'custom', cacheDir: 'node_modules/.vite-compile',
  server: { middlewareMode: true, hmr: false, watch: null }, optimizeDeps: { noDiscovery: true, entries: [] },
});
try {
  const { summarize, runBrief } = await server.ssrLoadModule('/agents/benchmark.js');
  if (args.includes('--report')) {
    report(summarize);
    console.log('benchmarks/results/benchmark.md written');
  } else {
    const { registry } = await server.ssrLoadModule('/lib/components/index.js');
    await server.ssrLoadModule('/lib/products/index.js');
    await server.ssrLoadModule('/lib/ops/index.js');
    const { preloadComponentAssets } = await server.ssrLoadModule('/lib/core/assets.js');
    await preloadComponentAssets(registry);
    const { createLlm } = await server.ssrLoadModule('/agents/llm.js');
    const { writeModel, runModel } = await server.ssrLoadModule('/server/simpyRun.js');
    const live = args.includes('--live');
    // --strong builder: those agents on the strong model (LLM_STRONG_AGENTS) for this run only.
    const strongAgents = opt('--strong');
    const llm = createLlm({ env: { ...loadEnv('development', ROOT, ''), ...(live ? { LLM_MODE: 'live' } : { LLM_MODE: 'mock' }), ...(strongAgents ? { LLM_STRONG_AGENTS: strongAgents } : {}) }, root: ROOT });
    const retries = opt('--retries') ? Number(opt('--retries')) : 2;
    const keys = new Set();
    const recording = { call: async (req) => { const r = await llm.call(req); if (r.source === 'live' || r.source === 'cache') keys.add(r.key); return r; } };
    const names = opt('--brief') ? [opt('--brief')] : index[opt('--set') ?? 'tuning'];
    if (!names) throw new Error(`no set "${opt('--set')}" (tuning, heldOut)`);
    console.log(`${live ? 'LIVE' : 'mock'}: ${names.length} brief(s)${strongAgents ? `, strong model for ${strongAgents}` : ''}, ${retries} retries per station; budget left $${llm.status().remaining.total.toFixed(4)} total, $${llm.status().remaining.session.toFixed(4)} this run`);
    const simpy = async (factory) => {
      const { dir } = writeModel({ root: mkdtempSync(join(tmpdir(), 'bench-')), registry, factory });
      return (await runModel(dir)).kpis;
    };
    for (const name of names) {
      const text = readFileSync(join(ROOT, 'benchmarks', 'briefs', `${name}.md`), 'utf8');
      const r = await runBrief({ registry, llm: recording, name, text, simpy, retries, critique: !args.includes('--no-critique'), log: (l) => console.log(`  ${l}`) });
      const { factory, ...run } = r;
      mkdirSync(join(RESULTS, 'runs'), { recursive: true });
      writeFileSync(join(RESULTS, 'runs', `${name}.json`), `${JSON.stringify({ ...run, mode: live ? 'live' : 'mock', models: { builder: strongAgents?.includes('builder') ? llm.config.models.strong.name : llm.config.models.default.name, others: llm.config.models.default.name }, retries, time: new Date().toISOString() }, null, 2)}\n`);
      if (factory) {
        mkdirSync(join(RESULTS, 'lines'), { recursive: true });
        writeFileSync(join(RESULTS, 'lines', `${name}.factory.json`), `${JSON.stringify(factory, null, 2)}\n`);
      }
      console.log(`${name}: ${r.stage}${r.reason ? ` (${r.reason.slice(0, 160)})` : ''} · $${r.totalCost.toFixed(4)} · ${r.seconds.toFixed(0)} s`);
      if (/budget:/.test(r.reason ?? '')) { console.log('budget cap reached: stopping'); break; }
    }
    if (live && !args.includes('--no-record')) {
      for (const k of keys) llm.record(k);
      console.log(`recorded ${keys.size} answer(s) into agents/fixtures/responses/`);
    }
    report(summarize);
    console.log(`benchmarks/results/benchmark.md written; budget left $${llm.status().remaining.total.toFixed(4)}`);
  }
} finally {
  await server.close();
}
