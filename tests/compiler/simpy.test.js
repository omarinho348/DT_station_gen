// The SimPy model (compiler/simpy.js, server/simpyRun.js, server/simpyApi.js; Phase 11 step 1): data from
// the timing table per unit, the generated model.py, its run (when Python and simpy are installed), the
// trace format, the KPIs, and agreement with the 3D twin's own played run.
import { describe, it, expect } from 'vitest';
import { readFileSync, mkdtempSync, mkdirSync, copyFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { registry } from '../../lib/components/index.js';
import '../../lib/products/index.js';
import '../../lib/ops/index.js';
import { preloadComponentAssets } from '../../lib/core/assets.js';
import { simData, emitSimPy } from '../../compiler/simpy.js';
import { writeModel, runModel, readResults } from '../../server/simpyRun.js';
import { createSimpyService } from '../../server/simpyApi.js';
import { review } from '../../agents/reviewer/deterministic.js';

const load = (name) => JSON.parse(readFileSync(`spec/examples/${name}.factory.json`, 'utf8'));
const hasSimpy = spawnSync(process.env.PYTHON || 'python', ['-c', 'import simpy'], { windowsHide: true }).status === 0;
const EVENTS = ['release', 'arrive', 'start', 'finish', 'reject', 'leave', 'exit'];

/** The twin's own played run time (the reviewer's play check). */
function playedSeconds(factory) {
  const f = review(registry, factory, { geometry: false }).findings.find((x) => x.check === 'play');
  return Number(f.message.match(/after ([\d.]+) s/)[1]);
}

describe('SimPy data and model', () => {
  it('per unit: cycle times and exit ports from the timing table; rejects by serial take the reject branch', () => {
    const d = simData(registry, load('bottling-line'));
    expect(d).toMatchObject({ line: 'bottlingLine', runSize: 10, holdSeconds: 0.25, entries: ['fill1', 'fill2'] });
    const inspect = d.stations.find((s) => s.id === 'inspect');
    // rejectEvery 4: serials 4 and 8 leave by the reject port, with the reject branch's time.
    expect(inspect.exit.map((p, i) => (p === 'reject' ? i + 1 : null)).filter(Boolean)).toEqual([4, 8]);
    expect(inspect.cycle[3]).not.toBe(inspect.cycle[0]);
    expect(d.units[3].facts).toEqual({ quality: 'reject' });
    expect(d.edges.find((e) => e.from === 'inspect' && e.fromPort === 'reject')).toMatchObject({ to: 'rework', toPort: 'input' });
    expect(d.edges.every((e) => e.duration >= 0 && e.capacity >= 1)).toBe(true);
  });

  it('the printer\'s rejects (verdict by serial) are parked on the reject lane in turn (its slot fact)', () => {
    const d = simData(registry, load('printer-line'));
    const st5 = d.stations.find((s) => s.id === 'st5');
    expect(d.units.filter((u) => u.facts.verdict === 'REJECT').map((u) => u.serial)).toEqual([5, 8]);
    expect(st5.exit.map((p, i) => (p === 'reject' ? i + 1 : null)).filter(Boolean)).toEqual([5, 8]);
  }, 60000);

  it('model.py: the fixed template with the data embedded; nothing random', () => {
    const d = simData(registry, load('bottling-line'));
    const py = emitSimPy(d, { source: 'spec/examples/bottling-line.factory.json' });
    expect(py).toMatch(/^"""SimPy model of the line "Juice bottling \(generic level\)" \(bottlingLine\)\./);
    expect(py).toContain('Generated by compiler/simpy.js from spec/examples/bottling-line.factory.json');
    expect(py).toContain(`DATA = json.loads(r'''${JSON.stringify(d)}''')`);
    expect(py).not.toMatch(/^\s*(import|from)\s+(random|numpy)/m); // no random source imported
    expect(emitSimPy(d)).toBe(emitSimPy(d)); // deterministic
  });
});

describe.skipIf(!hasSimpy)('SimPy runs (Python and simpy installed)', () => {
  it('bottling and printer: every unit out, the makespan within 0.5 % of the twin\'s played run; the trace format; the KPIs', async () => {
    await preloadComponentAssets(registry);
    for (const name of ['bottling-line', 'printer-line']) {
      const root = mkdtempSync(join(tmpdir(), 'simpy-'));
      const factory = load(name);
      const { dir, data } = writeModel({ root, registry, factory });
      const r = await runModel(dir);
      const k = r.kpis;
      expect(k.finished, name).toBe(true);
      expect(k.unitsOut).toBe(data.runSize);
      const played = playedSeconds(factory);
      expect(Math.abs(k.makespan - played) / played, `${name}: SimPy ${k.makespan} s vs played ${played} s`).toBeLessThan(0.005);
      // The trace: known events in time order; every unit released once and leaving once, after it entered.
      const t = r.trace;
      expect(t.every((e) => EVENTS.includes(e.event) && Number.isInteger(e.unit) && typeof e.station === 'string')).toBe(true);
      expect(t.every((e, i) => i === 0 || e.t >= t[i - 1].t - 1e-9)).toBe(true);
      for (let u = 1; u <= data.runSize; u += 1) {
        const mine = t.filter((e) => e.unit === u);
        expect(mine.filter((e) => e.event === 'release')).toHaveLength(1);
        expect(mine.filter((e) => e.event === 'exit')).toHaveLength(1);
        expect(mine[0].event).toBe('release');
        expect(mine.at(-1).event).toBe('exit');
      }
      expect(k.rejects.count).toBe(t.filter((e) => e.event === 'reject').length);
      expect(k.goodUnits + k.rejects.count).toBe(k.unitsOut);
      expect(Object.keys(k.utilisation).sort()).toEqual(data.stations.map((s) => s.id).sort());
      expect(Object.values(k.utilisation).every((u) => u > 0 && u <= 1)).toBe(true);
      expect(k.leadTime.min).toBeLessThanOrEqual(k.leadTime.mean);
      expect(k.wip.max).toBeGreaterThanOrEqual(1);
      expect(readResults(dir).kpis).toEqual(k);
    }
  }, 180000);

  it('the lubricant line runs to the end; its batch stations make it shorter than the twin (a known gap, under 10 %)', async () => {
    const root = mkdtempSync(join(tmpdir(), 'simpy-'));
    const factory = load('lubricant-line');
    const { dir } = writeModel({ root, registry, factory });
    const { kpis } = await runModel(dir);
    expect(kpis.finished).toBe(true);
    const played = playedSeconds(factory);
    expect(Math.abs(kpis.makespan - played) / played).toBeLessThan(0.1);
  }, 180000);

  it('/api/simpy: run an example, read its KPIs and its trace (since a time), refusals', async () => {
    const root = mkdtempSync(join(tmpdir(), 'simpy-api-'));
    mkdirSync(join(root, 'spec', 'examples'), { recursive: true });
    copyFileSync('spec/examples/bottling-line.factory.json', join(root, 'spec', 'examples', 'bottling-line.factory.json'));
    const svc = createSimpyService({ root, load: async () => ({ registry, writeModel, runModel, readResults }) });
    expect((await svc.handle({ method: 'GET', path: '/bottling-line/kpis.json' })).status).toBe(404);
    let r = await svc.handle({ method: 'POST', path: '/run', query: { example: 'bottling-line' } });
    expect(r.status).toBe(200);
    expect(r.body).toMatchObject({ folder: 'bottling-line', kpis: { finished: true, runSize: 10 } });
    expect(r.body.events).toBeGreaterThan(50);
    r = await svc.handle({ method: 'GET', path: '/bottling-line/kpis.json' });
    expect(r.body.goodUnits).toBe(8);
    r = await svc.handle({ method: 'GET', path: '/bottling-line/trace.jsonl', query: { since: '100' } });
    const events = r.text.trim().split('\n').map((l) => JSON.parse(l));
    expect(r.type).toBe('application/x-ndjson');
    expect(events.every((e) => e.t >= 100)).toBe(true);
    expect((await svc.handle({ method: 'POST', path: '/run', query: {} })).status).toBe(400);
    expect((await svc.handle({ method: 'POST', path: '/run', query: { line: 'nowhere' } })).status).toBe(404);
    expect((await svc.handle({ method: 'GET', path: '/../x/kpis.json' })).status).toBe(404);
  }, 120000);
});
